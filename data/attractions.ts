function unsplash(photoId: string) {
  return {
    imageUrl: `https://images.unsplash.com/${photoId}?w=800&q=80`,
    thumbnailUrl: `https://images.unsplash.com/${photoId}?w=400&q=60`,
  };
}

function attraction(
  data: Omit<Attraction, "imageUrl" | "thumbnailUrl"> & { photoId: string }
): Attraction {
  const { photoId, ...rest } = data;
  return { ...rest, ...unsplash(photoId) };
}

